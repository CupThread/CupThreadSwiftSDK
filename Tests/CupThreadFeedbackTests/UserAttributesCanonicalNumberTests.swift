    private struct MRRVector {
        let mrr: Double
        let mrrCanonical: String
        let expectedSignature: String
    }

    @Test func signaturePinsKnownServerMRRVectors() {
        // End-to-end vectors computed against the server's JS canonicalization
        // (Node: toFixed(2) + trailing-zero strip, then HMAC-SHA256), so any
        // regression in canonical formatting — not just the rounding mode — breaks
        // here. 10.125 is an exact dyadic tie ("10.13"); 9.995 exercises the exact
        // binary rounding basis ("9.99", the stored double is 9.994999…).
        let vectors = [
            MRRVector(
                mrr: 10.125,
                mrrCanonical: "10.13",
                expectedSignature: "4a6bf11e015e3d46565dbda9ffe9eeb42ed53a053a3c45d05cef1655648194d2"
            ),
            MRRVector(
                mrr: 9.995,
                mrrCanonical: "9.99",
                expectedSignature: "4e3471d68755f2eff52cc08a857192c777b03fff2596864c5f5b8e895e3f2bff"
            )
        ]
        let secret = "test_secret_key"
        for vector in vectors {
            let canonical = UserAttributesSigner.canonicalString(
                for: .init(
                    appKey: "app_demo",
                    userToken: "tok_123",
                    isPaying: true,
                    plan: "pro",
                    mrr: vector.mrr,
                    currency: "USD",
                    timestamp: 1773600000
                )
            )
            #expect(canonical.contains(vector.mrrCanonical))
            #expect(
                UserAttributesSigner.signature(for: canonical, secret: secret) == vector.expectedSignature,
                "HMAC vector mismatch for mrr \(vector.mrr) (canonical \(vector.mrrCanonical))"
            )
        }
    }
