    @Test func canonicalNumberMatchesServerToFixedSemantics() {
        // Spec examples (DATA-03)
        #expect(UserAttributesSigner.canonicalNumber(10.125) == "10.13")
        #expect(UserAttributesSigner.canonicalNumber(1200.005) == "1200.01")
        #expect(UserAttributesSigner.canonicalNumber(99.995) == "100")
        // Exact-binary rounding basis: the double for these literals sits below the
        // decimal value, so no carry happens even though the decimal ends in 5.
        #expect(UserAttributesSigner.canonicalNumber(9.995) == "9.99")
        #expect(UserAttributesSigner.canonicalNumber(2.675) == "2.67")
        #expect(UserAttributesSigner.canonicalNumber(0.025) == "0.03")
        #expect(UserAttributesSigner.canonicalNumber(1.005) == "1")
        #expect(UserAttributesSigner.canonicalNumber(4.995) == "5")
        #expect(UserAttributesSigner.canonicalNumber(12.555) == "12.55")
        #expect(UserAttributesSigner.canonicalNumber(12.545) == "12.54")
        #expect(UserAttributesSigner.canonicalNumber(1.145) == "1.15")
        #expect(UserAttributesSigner.canonicalNumber(1.135) == "1.14")
        // Dyadic exact ties round away from zero, matching Node's observable
        // toFixed behavior on both signs.
        #expect(UserAttributesSigner.canonicalNumber(1.125) == "1.13")
        #expect(UserAttributesSigner.canonicalNumber(0.125) == "0.13")
        #expect(UserAttributesSigner.canonicalNumber(0.625) == "0.63")
        #expect(UserAttributesSigner.canonicalNumber(12.125) == "12.13")
        #expect(UserAttributesSigner.canonicalNumber(8.875) == "8.88")
        #expect(UserAttributesSigner.canonicalNumber(-1.125) == "-1.13")
        #expect(UserAttributesSigner.canonicalNumber(-0.625) == "-0.63")
        // A negative value rounding below one cent keeps its sign ("-" + "0");
        // -0.005 itself sits above the decimal literal and carries to "-0.01".
        #expect(UserAttributesSigner.canonicalNumber(-0.004) == "-0")
        #expect(UserAttributesSigner.canonicalNumber(-0.005) == "-0.01")
        // Negative zero normalizes like JS ToString.
        #expect(UserAttributesSigner.canonicalNumber(-0.0) == "0")
        // Existing renderings keep passing.
        #expect(UserAttributesSigner.canonicalNumber(1200.0) == "1200")
        #expect(UserAttributesSigner.canonicalNumber(99.5) == "99.5")
        #expect(UserAttributesSigner.canonicalNumber(12.34) == "12.34")
        #expect(UserAttributesSigner.canonicalNumber(0.0) == "0")
    }

