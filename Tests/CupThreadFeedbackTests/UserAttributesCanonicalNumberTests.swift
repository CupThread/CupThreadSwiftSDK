/// Pins `UserAttributesSigner.canonicalNumber` and the signed MRR vectors to the
/// server's JavaScript canonicalization (ECMA-262 `toFixed(2)` on the exact binary
/// double + trailing-zero strip, DATA-03). Pure functions — no client state.
