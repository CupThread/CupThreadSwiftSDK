// The 0.1.0 CDN object predates this release pipeline and its exact source
// provenance is unverifiable (issues #11 and #55). It must never be repointed
// or overwritten, so the version itself is unreleasable.
export const RESERVED_VERSIONS = {
  "0.1.0": "the CDN object CupThreadFeedback-0.1.0.xcframework.zip predates this release pipeline and its exact source provenance is unverifiable (issues #11 and #55); publish 0.1.1 or later instead"
};
const VERSION_FILE = "Sources/CupThreadFeedback/SDKVersion.swift";

// --- Exported for ReleasePreflightTests: pure version helpers -------------

export function isSemver(version) {
  return /^\d+\.\d+\.\d+$/.test(version);
}

export function compareSemver(a, b) {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  if (pa.length !== 3 || pb.length !== 3 || pa.some(Number.isNaN) || pb.some(Number.isNaN)) {
    throw new Error(`Invalid semver: ${JSON.stringify(a)}, ${JSON.stringify(b)}`);
  }
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pa[i] < pb[i] ? -1 : 1;
  }
  return 0;
}

// Greatest tag of the form vX.Y.Z, or null when the repository has none yet.
export function greatestVersionTag(tagNames) {
  const tags = tagNames.filter((name) => /^v\d+\.\d+\.\d+$/.test(name));
  if (tags.length === 0) return null;
  return tags.sort((a, b) => compareSemver(a.slice(1), b.slice(1)))[tags.length - 1];
}

export function artifactFilename(version) {
  return `CupThreadFeedback-${version}.xcframework.zip`;
}

export function sdkVersionFileContent(version) {
  return `// Generated by scripts/release.mjs — do not edit manually.
import Foundation

extension FeedbackClient {
    /// The current semantic version of the CupThread Apple SDK.
    public static let sdkVersion = "${version}"

    /// The SDK identifier reported in submission metadata and request headers.
    public static let sdkName = "cupthread-apple"

    /// The formatted SDK descriptor combining name and version (e.g. \`cupthread-apple/0.1.0\`).
    public static var sdkIdentifier: String {
        "\\(sdkName)/\\(sdkVersion)"
    }
}
`;
}

export function syncSDKVersion(version) {
  const versionFile = path.join(ROOT, VERSION_FILE);
  const content = sdkVersionFileContent(version);
  if (existsSync(versionFile) && readFileSync(versionFile, "utf8") === content) {
    return false;
  }
  writeFileSync(versionFile, content, "utf8");
  return true;
}

// --- Exported for ReleasePreflightTests: pure preflight decisions ----------
//
// evaluateReleaseReadiness turns probed repository/remote state into pass/fail
// decisions without touching git, gh, or the network, so `swift test` can pin
// every rule. `artifactSha256` is null during the pre-build preflight and set
// during the post-build re-evaluation; several rules only fire once the
// freshly built artifact's checksum is known.

export function evaluateReleaseReadiness(facts) {
  const errors = [];
  const warnings = [];
  const completed = { tag: false, githubRelease: false, cdnObject: false };
  const version = facts.version;
  const tag = `v${version}`;
  const artifact = artifactFilename(version);

  if (facts.version && !isSemver(facts.version)) {
    errors.push(`Version ${facts.version} is not plain semver (expected X.Y.Z).`);
  }

  if (facts.branch !== RELEASE_BRANCH) {
    errors.push(`Releases must be cut from ${RELEASE_BRANCH} (found: ${facts.branch || "none"}). Switch with: git switch ${RELEASE_BRANCH}`);
  }

  if (isToleratedPendingVersionState(facts)) {
    warnings.push(`Working tree carries the generated ${VERSION_FILE} from a previous release attempt; it will be committed for this release.`);
  } else if (facts.statusLines && facts.statusLines.length > 0) {
    errors.push(`Working tree is not clean — commit or stash everything before releasing. git status --porcelain:\n    ${facts.statusLines.join("\n    ")}`);
  }

  if (facts.fetchError) {
    errors.push(`Could not fetch origin to compare ${RELEASE_BRANCH} ancestry: ${facts.fetchError}`);
  } else if (facts.headSha && facts.originMainSha && facts.originMainSha !== facts.headSha && facts.originMainIsAncestorOfHead === false) {
    errors.push(`Local ${RELEASE_BRANCH} (${shortSha(facts.headSha)}) is behind or diverged from origin/${RELEASE_BRANCH} (${shortSha(facts.originMainSha)}). Fast-forward with: git merge --ff-only origin/${RELEASE_BRANCH}`);
  }

  if (RESERVED_VERSIONS[version]) {
    errors.push(`Version ${version} is reserved and must not be republished: ${RESERVED_VERSIONS[version]}`);
  }

  const latestTag = facts.latestTag;
  if (latestTag && latestTag !== tag) {
    const latestVersion = latestTag.slice(1);
    if (!isSemver(latestVersion)) {
      warnings.push(`Latest version tag ${latestTag} is not plain semver; skipping the version-monotonicity check.`);
    } else if (compareSemver(version, latestVersion) <= 0) {
      errors.push(`Version ${version} is not greater than the latest release tag ${latestTag}. Pick a higher version.`);
    }
  }

  if (facts.remoteTagProbeError) {
    errors.push(`Could not list remote tags to check for an existing ${tag}: ${facts.remoteTagProbeError}`);
  } else {
    if (facts.localTagCommitSha && facts.localTagCommitSha !== facts.headSha) {
      errors.push(`Tag ${tag} already exists locally at ${shortSha(facts.localTagCommitSha)} but HEAD is ${shortSha(facts.headSha)}. Move to that commit or delete the tag with: git tag -d ${tag}`);
    }
    if (facts.remoteTagCommitSha && facts.remoteTagCommitSha !== facts.headSha) {
      errors.push(`Tag ${tag} already exists on origin at ${shortSha(facts.remoteTagCommitSha)} but HEAD is ${shortSha(facts.headSha)} — refusing to move a remote tag.`);
    }
    if (facts.localTagCommitSha && facts.localTagCommitSha === facts.headSha) {
      if (facts.remoteTagCommitSha === facts.headSha) {
        completed.tag = true;
      } else {
        warnings.push(`Tag ${tag} exists locally at HEAD but has not been pushed; it will be pushed during publication.`);
      }
    }
  }

  const release = facts.githubRelease;
  if (release) {
    if (release.isDraft) {
      warnings.push(`A draft GitHub release for ${tag} already exists; its assets will be replaced with the freshly built artifact.`);
    } else if (facts.artifactSha256) {
      if (!release.assetNames.includes(artifact)) {
        errors.push(`GitHub release ${tag} is already published but has no ${artifact} asset — treating ${version} as releasable would leave an ambiguous state. Publish a new version instead.`);
      } else if (release.bodySha256 && release.bodySha256 !== facts.artifactSha256) {
        errors.push(`Published GitHub release ${tag} advertises checksum ${release.bodySha256} but this build is ${facts.artifactSha256} — mismatched artifact, refusing to continue.`);
      } else {
        completed.githubRelease = true;
      }
    } else {
      warnings.push(`GitHub release ${tag} is already published; the freshly built artifact will be checked against it before anything is uploaded.`);
    }
  }

  const cdn = facts.cdnObject;
  if (cdn && cdn.exists) {
    if (!facts.artifactSha256) {
      warnings.push(`CDN object ${artifact} already exists; its checksum will be verified against the freshly built artifact before any upload.`);
    } else if (cdn.sha256 === facts.artifactSha256) {
      completed.cdnObject = true;
    } else if (release && !release.isDraft) {
      errors.push(`CDN object ${artifact} exists with checksum ${cdn.sha256} but this build is ${facts.artifactSha256}, and the GitHub release is already published — refusing to mutate a published artifact.`);
    } else {
      warnings.push(`CDN object ${artifact} exists with a different checksum (${cdn.sha256}); the release is unpublished, so publication will overwrite it with the verified build.`);
    }
  }

  return { errors, warnings, completed };
}

// A dirty tree is fatal — except for exactly one state: the generated
// version file left uncommitted by a previous release attempt of the same
// version. Reruns recognize it instead of forcing a manual checkout.
function isToleratedPendingVersionState(facts) {
  if (facts.versionFilePendingRelease !== true) return false;
  const lines = facts.statusLines || [];
  return lines.length > 0 && lines.every((line) => line.slice(3) === VERSION_FILE);
}

function shortSha(sha) {
  return sha ? sha.slice(0, 12) : "none";
}

// --- Probing (impure): turn git/gh/CDN state into preflight facts ----------

function probe(cmd, args, opts = {}) {
  const result = spawnSync(cmd, args, {
    cwd: opts.cwd ?? ROOT,
    stdio: ["ignore", "pipe", "pipe"],
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024
  });
  return {
    ok: result.status === 0 && !result.error,
    status: result.status,
    stdout: (result.stdout || "").trim(),
    stderr: (result.stderr || "").trim()
  };
}

function requireCommands(commands) {
  const missing = commands.filter((cmd) => !probe("sh", ["-c", `command -v ${cmd}`]).ok);
  if (missing.length > 0) {
    fail(`Missing required tools: ${missing.join(", ")} — install them before releasing.`);
  }
}

function requireGhAuth() {
  if (!probe("gh", ["auth", "status"]).ok) {
    fail("gh is not authenticated — run `gh auth login` before releasing.");
  }
}

function gitStatusLines() {
  return probe("git", ["status", "--porcelain"]).stdout.split("\n").filter(Boolean);
}

function gitHeadSha() {
  const out = probe("git", ["rev-parse", "HEAD"]);
  return out.ok ? out.stdout : null;
}

function gitBranch() {
  const out = probe("git", ["rev-parse", "--abbrev-ref", "HEAD"]);
  return out.ok ? out.stdout : null;
}

function localTagCommitSha(tag) {
  const out = probe("git", ["rev-parse", "-q", "--verify", `${tag}^{commit}`]);
  return out.ok ? out.stdout : null;
}

// For annotated tags ls-remote lists both the tag object and the peeled
// `^{}` commit; lightweight tags list the commit directly. Either way the
// returned sha is the commit the tag names.
function remoteTagCommitSha(tag) {
  const out = probe("git", ["ls-remote", "origin", `refs/tags/${tag}`, `refs/tags/${tag}^{}`]);
  if (!out.ok) return { sha: null, error: out.stderr || `git ls-remote exited ${out.status}` };
  const lines = out.stdout.split("\n").filter(Boolean);
  const peeled = lines.find((line) => line.endsWith(`refs/tags/${tag}^{}`));
  const plain = lines.find((line) => line.endsWith(`refs/tags/${tag}`));
  return { sha: peeled ? peeled.split("\t")[0] : (plain ? plain.split("\t")[0] : null), error: null };
}

function githubReleaseInfo(tag) {
  const out = probe("gh", ["release", "view", tag, "--json", "isDraft,assets,body"]);
  if (!out.ok) return null; // "release not found" — anything else is caught by requireGhAuth
  try {
    const parsed = JSON.parse(out.stdout);
    const body = typeof parsed.body === "string" ? parsed.body : "";
    const checksumIndex = body.indexOf("checksum ");
    const bodySha256 = checksumIndex >= 0 ? (body.slice(checksumIndex + "checksum ".length).match(/^[0-9a-f]{64}/) || [null])[0] : null;
    return {
      isDraft: parsed.isDraft === true,
      assetNames: (parsed.assets || []).map((asset) => asset.name),
      bodySha256
    };
  } catch {
    return null;
  }
}

// Probe the published CDN object (if any). A random query parameter busts
// CDN caches so the check observes the object itself, not a cached copy.
function cdnObjectInfo(filename) {
  const url = `${CDN_BASE}/sdks/apple/${filename}?probe=${process.pid}-${Date.now()}`;
  const dir = mkdtempSync(path.join(tmpdir(), "cupthread-cdn-probe-"));
  try {
    const file = path.join(dir, "object.bin");
    const out = probe("curl", ["-fsSL", "-o", file, "--max-time", "120", url]);
    if (!out.ok) return { exists: false };
    return { exists: true, sha256: sha256(file) };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function collectPreflightFacts(version, planUpload) {
  const facts = {
    version,
    branch: gitBranch(),
    statusLines: gitStatusLines(),
    versionFilePendingRelease: false,
    headSha: gitHeadSha(),
    originMainSha: null,
    originMainIsAncestorOfHead: false,
    fetchError: null,
    latestTag: null,
    localTagCommitSha: null,
    remoteTagCommitSha: null,
    remoteTagProbeError: null,
    githubRelease: null,
    cdnObject: null
  };

  const versionFile = path.join(ROOT, VERSION_FILE);
  facts.versionFilePendingRelease = existsSync(versionFile)
    && readFileSync(versionFile, "utf8") === sdkVersionFileContent(version);

  const fetched = probe("git", ["fetch", "origin", RELEASE_BRANCH, "--quiet"]);
  if (fetched.ok) {
    const origin = probe("git", ["rev-parse", `origin/${RELEASE_BRANCH}`]);
    facts.originMainSha = origin.ok ? origin.stdout : null;
    facts.originMainIsAncestorOfHead = probe("git", ["merge-base", "--is-ancestor", `origin/${RELEASE_BRANCH}`, "HEAD"]).ok;
  } else {
    facts.fetchError = fetched.stderr || `git fetch exited ${fetched.status}`;
  }

  facts.latestTag = greatestVersionTag(
    probe("git", ["tag", "--list", "v*"]).stdout.split("\n").filter(Boolean)
  );
  facts.localTagCommitSha = localTagCommitSha(`v${version}`);
  const remote = remoteTagCommitSha(`v${version}`);
  facts.remoteTagCommitSha = remote.sha;
  facts.remoteTagProbeError = remote.error;
  facts.githubRelease = githubReleaseInfo(`v${version}`);
  if (planUpload) {
    facts.cdnObject = cdnObjectInfo(artifactFilename(version));
  }
  return facts;
}

function runPreflight(version, planUpload) {
  requireCommands(["git", "gh", "swift", "xcodebuild", "curl", "npx", "libtool", "lipo", "nm", "ditto"]);
  requireGhAuth();
  const { facts, collectErrors } = collectPreflightFactsWithErrors(version, planUpload);
  const decision = evaluateReleaseReadiness(facts);
  for (const warning of decision.warnings) console.log(`  ⚠︎ ${warning}`);
  const errors = [...collectErrors, ...decision.errors];
  if (errors.length > 0) {
    console.error("✗ Release preflight failed:");
    for (const error of errors) console.error(`  - ${error}`);
    console.error("  See docs/release-runbook.md for remedies.");
    process.exit(1);
  }
  console.log("  preflight OK");
  return facts;
}

function collectPreflightFactsWithErrors(version, planUpload) {
  const collectErrors = [];
  const facts = collectPreflightFacts(version, planUpload);
  if (!facts.headSha) collectErrors.push("Could not resolve HEAD — is this a git checkout?");
  return { facts, collectErrors };
}

// --- Publication helpers ---------------------------------------------------

// run() throws instead of exiting so publication steps can wrap failures
// with recovery instructions; main()'s catch converts throws to exit 1.
function run(cmd, args, opts = {}) {
  console.log(`  $ ${cmd} ${args.join(" ")}`);
  const result = spawnSync(cmd, args, {
    cwd: opts.cwd ?? ROOT,
    stdio: opts.capture ? ["ignore", "pipe", "inherit"] : "inherit",
    encoding: "utf8",
    // `nm` on a slice archive emits megabytes of symbols; the 1MB default
    // maxBuffer would SIGTERM the child and lose the output.
    maxBuffer: 64 * 1024 * 1024
  });
  if (result.error) throw new Error(`Command failed: ${cmd} ${args.join(" ")} (${result.error.message})`);
  if (result.status !== 0) throw new Error(`Command failed (${result.status}): ${cmd} ${args.join(" ")}`);
  return result.stdout;
}

function withRecovery(step, recovery, fn) {
  try {
    return fn();
  } catch (error) {
    console.error(`✗ ${step}: ${error.message}`);
    console.error(`  RECOVERY: ${recovery}`);
    process.exit(1);
  }
}

function fail(message) {
  console.error(`✗ ${message}`);
  process.exit(1);
}

function sha256(file) {
  const hash = createHash("sha256");
  hash.update(readFileSync(file));
  return hash.digest("hex");
}

function parseArgs(argv) {
  const args = { dryRun: false, skipTests: false, yes: false, version: null, skipUpload: false, syncVersionOnly: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--version") args.version = argv[++i];
    else if (arg === "--dry-run") args.dryRun = true;
    else if (arg === "--skip-tests") args.skipTests = true;
    else if (arg === "--skip-upload") args.skipUpload = true;
    else if (arg === "--yes") args.yes = true;
    else if (arg === "--sync-version-only") args.syncVersionOnly = true;
    else fail(`Unknown argument: ${arg}`);
  }
  if (!args.version || !isSemver(args.version)) {
    fail("--version must be specified as semver, e.g. --version 0.1.0");
  }
  return args;
}

function humanSize(bytes) {
  if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

