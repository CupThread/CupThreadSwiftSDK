async function verifyStaticConsumer(zipPath, work) {
  const consumer = path.join(work, "consumer-probe");
  rmSync(consumer, { recursive: true, force: true });
  mkdirSync(path.join(consumer, "Sources", "ConsumerProbe"), { recursive: true });
  // SwiftPM rejects absolute paths for local binary targets — the probe
  // package sits next to the zip, so a relative path is one `..` away.
  const relativeZip = path.relative(consumer, path.resolve(zipPath));
  writeFileSync(path.join(consumer, "Package.swift"), `// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "ConsumerProbe",
    platforms: [.macOS(.v14)],
    targets: [
        .binaryTarget(name: "CupThreadFeedback", path: "${relativeZip.replace(/"/g, '\\"')}"),
        .executableTarget(name: "ConsumerProbe", dependencies: ["CupThreadFeedback"])
    ]
)
`);
  writeFileSync(path.join(consumer, "Sources", "ConsumerProbe", "main.swift"), `import Foundation
import CupThreadFeedback

let configuration = FeedbackClientConfiguration(
    baseURL: URL(string: "https://api.cupthread.com")!,
    appKey: "${CONSUMER_APP_KEY}"
)
let client = FeedbackClient(configuration: configuration)
print("probe:", client.configuration.appKey, FeedbackPlatform.current)
`);
  console.log("• verifying binary channel with a consumer probe package");
  run("swift", ["build"], { cwd: consumer });
  const probeOutput = run(path.join(consumer, ".build", "debug", "ConsumerProbe"), [], { capture: true, cwd: consumer });
  if (!probeOutput.includes(CONSUMER_APP_KEY)) {
    throw new Error(`Consumer probe printed unexpected output: ${probeOutput.trim()}`);
  }

  const buildDir = path.join(consumer, ".build");
  const visit = (dir, onEntry) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(full, onEntry);
      else onEntry(full);
    }
  };
  visit(buildDir, (file) => {
    if (file.endsWith(".dylib") && path.basename(file).startsWith("libCupThreadFeedback")) {
      throw new Error(`Consumer build produced a CupThreadFeedback dylib: ${file}`);
    }
  });
  const executable = path.join(buildDir, "debug", "ConsumerProbe");
  const loads = run("otool", ["-L", executable], { capture: true });
  if (loads.includes("CupThreadFeedback")) {
    throw new Error(`Consumer binary still loads CupThreadFeedback dynamically:\n${loads}`);
  }
  const symbols = run("nm", [executable], { capture: true });
  if (!symbols.includes("17CupThreadFeedback")) {
    throw new Error("Consumer binary does not statically contain CupThreadFeedback symbols");
  }
  console.log("  consumer probe: module import, static linkage, and runtime OK");
}

function verifyCdnChecksum(filename, expectedSha256) {
  console.log("• verifying the uploaded CDN object's checksum");
  const info = cdnObjectInfo(filename);
  if (!info.exists) {
    fail(`CDN object ${filename} is not reachable right after upload (propagation or cache issue?). The GitHub release is still a draft; check ${CDN_BASE}/sdks/apple/${filename} and rerun — the rerun recognizes the tag and the draft release.`);
  }
  if (info.sha256 !== expectedSha256) {
    fail(`CDN object ${filename} serves checksum ${info.sha256} but the verified build is ${expectedSha256}. The GitHub release is still a draft; overwrite the R2 object and rerun.`);
  }
  console.log(`  sha256:${expectedSha256} verified on CDN`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const version = args.version;

  if (args.syncVersionOnly) {
    const changed = syncSDKVersion(version);
    console.log(changed ? `✓ Synced SDK version to ${version}` : `✓ SDK version already at ${version}`);
    return;
  }

  if (args.dryRun) {
    console.log("• [dry-run] skipping release preflight — branch, ancestry, tag, release, and CDN collision checks only guard real publications");
  } else {
    console.log("• preflight");
    runPreflight(version, !args.skipUpload);
  }

  if (!args.dryRun && !args.yes) {
    if (!process.stdout.isTTY) fail("Refusing to publish without --yes (or use --dry-run).");
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question(`Release Apple SDK v${version} to ${CDN_BASE} + GitHub? [y/N] `);
    rl.close();
    if (!/^y(es)?$/i.test(answer.trim())) fail("Aborted.");
  }

  console.log(`\n🍎 Building CupThread Apple SDK v${version}`);
  const work = path.join(ROOT, "build/release");
  rmSync(work, { recursive: true, force: true });
  mkdirSync(work, { recursive: true });

  if (!args.dryRun) {
    console.log(`• syncing SDK version to ${version}`);
    if (syncSDKVersion(version)) {
      run("git", ["add", VERSION_FILE]);
      const status = run("git", ["status", "--porcelain", VERSION_FILE], { capture: true });
      if (status && status.trim()) {
        run("git", ["commit", "-m", `chore: bump SDK version to ${version}`]);
      }
    }
  } else {
    console.log(`• [dry-run] would sync SDK version constant to ${version}`);
  }

  if (!args.skipTests) {
    console.log("• swift test");
    run("swift", ["test"], { cwd: ROOT });
  }

  console.log("• archiving platform slices");
  const frameworks = [];
  for (const slice of APPLE_SLICES) {
    const derivedData = path.join(work, "derived-data", slice.name);
    run("xcodebuild", [
      "archive",
      "-scheme", "CupThreadFeedback",
      "-destination", slice.destination,
      "-archivePath", path.join(work, `${slice.name}.xcarchive`),
      "-derivedDataPath", derivedData,
      "SKIP_INSTALL=NO",
      "BUILD_LIBRARY_FOR_DISTRIBUTION=YES",
      "-quiet"
    ], { cwd: ROOT });
    frameworks.push(stageStaticFramework(slice, path.join(work, `${slice.name}.xcarchive`), derivedData, work, version));
  }

  console.log("• verifying static framework slices");
  for (const slice of APPLE_SLICES) {
    const framework = path.join(work, "static", slice.name, "CupThreadFeedback.framework");
    if (!existsSync(framework)) {
      throw new Error(`Missing static framework slice for ${slice.name} at: ${framework}`);
    }
    const binary = path.join(framework, slice.name === "macos"
      ? path.join("Versions", "A", "CupThreadFeedback")
      : "CupThreadFeedback");
    if (!existsSync(binary)) {
      throw new Error(`Missing static binary for ${slice.name} at: ${binary}`);
    }
    verifyStaticBinary(framework, SLICE_ARCHS[slice.name]);
    verifyPrivacyManifest(framework, `Static framework slice ${slice.name}`);
  }

  console.log("• assembling XCFramework");
  const xcframework = path.join(work, "CupThreadFeedback.xcframework");
  run("xcodebuild", ["-create-xcframework", ...frameworks.flatMap((f) => ["-framework", f]), "-output", xcframework]);

  console.log("• verifying static XCFramework slices");
  verifyStaticXCFramework(xcframework);

  console.log("• staging resource bundle");
  const sourceLprojs = readdirSync(path.join(ROOT, "Sources", "CupThreadFeedback", "Resources"))
    .filter((name) => name.endsWith(".lproj"));
  const releaseDir = path.join(work, `CupThreadFeedback-${version}`);
  mkdirSync(releaseDir, { recursive: true });
  run("cp", ["-R", xcframework, path.join(releaseDir, "CupThreadFeedback.xcframework")]);
  run("cp", ["-R", findBuiltResourceBundle(path.join(work, "derived-data", "ios"), "ios"), path.join(releaseDir, RESOURCE_BUNDLE_NAME)]);
  run("cp", [path.join(ROOT, "LICENSE"), path.join(releaseDir, "LICENSE")]);
  writeFileSync(path.join(releaseDir, "INSTALL.md"), installInstructionsMarkdown(version));
  verifyResourceBundle(path.join(releaseDir, RESOURCE_BUNDLE_NAME), sourceLprojs);

  const filename = artifactFilename(version);
  const zipPath = path.join(work, filename);
  run("ditto", ["-c", "-k", "--sequesterRsrc", "--keepParent", releaseDir, zipPath]);

  const artifact = {
    name: "XCFramework (iOS · macOS · visionOS · tvOS, static)",
    filename,
    url: `${CDN_BASE}/sdks/apple/${filename}`,
    size: humanSize(statSync(zipPath).size),
    sha256: sha256(zipPath)
  };
  console.log(`  ${filename}  ${artifact.size}  sha256:${artifact.sha256}`);

  await verifyStaticConsumer(zipPath, work);

  const releaseInfo = {
    sdk: "apple",
    version,
    date: new Date().toISOString().slice(0, 10),
    artifact,
    notes: [
      `CupThread Apple SDK v${version}`,
      "Static-library XCFramework: hosts link the SDK into their own binary (no embedded dylib, dead-code stripping applies).",
      "The zip carries the localized-strings bundle — add it to your app target's Copy Bundle Resources (see INSTALL.md).",
      "Every framework slice ships a PrivacyInfo.xcprivacy manifest (UserDefaults CA92.1 + collected-data types), aggregated automatically by Xcode 15+.",
      "SwiftUI surfaces: roadmap board, What's New, feature requests, feedback composer.",
      "iOS 17+ · macOS 14+ (universal arm64 + x86_64) · visionOS 1.0+ · tvOS 17+.",
      `Binary target with checksum ${artifact.sha256}.`
    ]
  };

  const infoFile = path.join(work, "release-info.json");
  writeFileSync(infoFile, JSON.stringify(releaseInfo, null, 2) + "\n");

  if (args.dryRun) {
    console.log(`\n  [dry-run] Apple SDK v${version} built successfully.`);
    return;
  }

  // Publication order (issue #11): tag the exact build commit → draft GitHub
  // release with the artifact attached → R2 upload → CDN checksum
  // verification → only then publish the draft. Nothing becomes public
  // half-verified, and every stage is safe to rerun.

  console.log("• verifying publication state against the fresh artifact");
  const { facts, collectErrors } = collectPreflightFactsWithErrors(version, !args.skipUpload);
  const decision = evaluateReleaseReadiness({ ...facts, artifactSha256: artifact.sha256 });
  for (const warning of decision.warnings) console.log(`  ⚠︎ ${warning}`);
  if (collectErrors.length > 0 || decision.errors.length > 0) {
    console.error("✗ Publication state check failed:");
    for (const error of [...collectErrors, ...decision.errors]) console.error(`  - ${error}`);
    console.error("  See docs/release-runbook.md for remedies.");
    process.exit(1);
  }

  if (decision.completed.tag && decision.completed.githubRelease && decision.completed.cdnObject) {
    console.log(`\n✓ Apple SDK v${version} is already fully released — tag, GitHub release, and CDN object all match this exact build. Nothing to do.`);
    return;
  }

  const tag = `v${version}`;
  const notes = releaseInfo.notes.map((n) => `- ${n}`).join("\n");

  if (!decision.completed.tag) {
    if (!facts.localTagCommitSha) {
      run("git", ["tag", "-a", tag, "-m", `Release ${tag}`]);
    }
    withRecovery(
      "tag push failed",
      `nothing is published yet (the tag exists locally). Resolve the push, or drop the local tag with \`git tag -d ${tag}\`, then rerun — the rerun recognizes the tag state.`,
      () => run("git", ["push", "origin", tag])
    );
    const pushed = remoteTagCommitSha(tag);
    if (pushed.error || pushed.sha !== facts.headSha) {
      fail(`Tag ${tag} on origin does not point at the release commit ${shortSha(facts.headSha)} after push.`);
    }
    console.log(`  tag ${tag} pushed at ${shortSha(facts.headSha)}`);
  } else {
    console.log(`  tag ${tag} is already on origin at HEAD — keeping it`);
  }

  if (decision.completed.githubRelease) {
    console.log("  GitHub release is already published with a matching artifact — leaving it untouched");
  } else if (facts.githubRelease && facts.githubRelease.isDraft) {
    withRecovery(
      "asset upload to the existing draft release failed",
      "the tag is pushed but nothing is published. Fix the issue and rerun — the draft release is recognized and its assets replaced.",
      () => run("gh", ["release", "upload", tag, zipPath, "--clobber"])
    );
  } else {
    withRecovery(
      "draft GitHub release creation failed",
      `the tag is pushed but nothing is published. Inspect with \`gh release view ${tag}\` and rerun — a matching draft is reused.`,
      () => run("gh", ["release", "create", tag, "--draft", "--title", `Apple SDK v${version}`, "--notes", notes, zipPath])
    );
  }

  if (args.skipUpload) {
    console.log("• [skip-upload] leaving the GitHub release as a draft — rerun without --skip-upload to upload the CDN artifact and publish");
    return;
  }

  if (decision.completed.cdnObject) {
    console.log("  CDN object already matches this build — skipping upload");
  } else {
    withRecovery(
      "R2 upload failed",
      "the GitHub release is still a draft and nothing is public. Fix credentials or connectivity and rerun — the tag and the draft release are recognized and reused.",
      () => run("npx", ["wrangler", "r2", "object", "put", `${R2_BUCKET}/sdks/apple/${filename}`,
        "--file", zipPath, "--remote", "--content-type", "application/zip"])
    );
    verifyCdnChecksum(filename, artifact.sha256);
  }

  if (facts.githubRelease && !facts.githubRelease.isDraft) {
    console.log("  GitHub release was already published");
  } else {
    withRecovery(
      "publishing the draft release failed",
      `the CDN artifact is uploaded and verified. After checking the ${filename} asset yourself, publish manually with: gh release edit ${tag} --draft=false`,
      () => run("gh", ["release", "edit", tag, "--draft=false"])
    );
  }

  console.log(`\n✓ Apple SDK v${version} successfully released!`);
  console.log("  Next manual steps:");
  console.log(`  - git push origin ${RELEASE_BRANCH}   (publishes the SDK version bump commit)`);
  console.log("  - update the README install snippet if this version becomes the documented one");
}

// Importing this module (as ReleasePreflightTests does) must be side-effect
// free; main() runs only when the script is executed directly.
function isDirectInvocation() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isDirectInvocation()) {
  main().catch((err) => fail(err.stack || err.message));
}
